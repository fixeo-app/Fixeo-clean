test('W5 Bio migration creates only its approved RPC and leaves table rights and triggers intact',()=>{
 for(const keyword of ['DROP','DELETE','TRUNCATE'])assert.doesNotMatch(sql,new RegExp('\\b'+keyword+'\\b','i'));
 assert.equal((sql.match(/CREATE FUNCTION/g)||[]).length,1);
 assert.match(sql,/SET description = v_description\s+WHERE id = v_artisan_id AND owner_user_id = auth.uid\(\)/);
 assert.doesNotMatch(sql,/ALTER TABLE|CREATE TRIGGER|ALTER FUNCTION|GRANT.*ON TABLE|SET\s+updated_at/i);
 const top=sql.replace(/\$w5_bio\$[\s\S]*?\$w5_bio\$/,"'body'").replace(/--[^\n]*/g,'');
 assert.doesNotMatch(top,/(?:^|;)\s*(?:INSERT|UPDATE|DELETE|TRUNCATE|CALL|SELECT)\b/i);
});
