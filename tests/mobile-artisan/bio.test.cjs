const authority=fs.readFileSync('supabase/migrations/20261005085640_mobile_w5_artisan_authority_v2.sql','utf8').split('-- W5_AUTHORITY_CORE_BEGIN')[1].split('-- W5_AUTHORITY_CORE_END')[0];
