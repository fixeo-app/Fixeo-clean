-- Phase: 7C.9E / 7C.9F / 7C.9F.1
-- Version: 1.1 — 2026-08-10 (corrected from 1.0)
--
-- CHANGES IN VERSION 1.1 (7C.9F.1 surgical patch):
--   - REMOVED redundant CREATE UNIQUE INDEX idx_ecr_context_id.
--     The UNIQUE constraint already owns a unique index.
--     Having both creates a duplicate index, confuses VQ-4 count,
--     and wastes storage. Canonical uniqueness mechanism is the
--     named UNIQUE constraint only.
--   - STRENGTHENED authenticated/anon grants:
--     REVOKE ALL from both anon AND authenticated before re-granting.
--     Sequence USAGE/SELECT explicitly revoked from anon and authenticated
--     (no SELECT operation needs sequence access).
--   - VERIFIED profiles admin contract:
--     profiles.id = auth.uid() AND profiles.role = 'admin'
--     is the established FIXEO admin pattern used by 10+ existing RLS
--     policies across enterprise_leads, notifications-table,
--     rls-fix-2026-04-29, rls-claim-requests, rls-artisan-* files.
--     public.profiles has columns: id (UUID), role (TEXT).
--     Contract is proved by existing production migration history.
--     ecr_admin_select policy is UNCHANGED.
--   - UPDATED verification queries (VQ-1 through VQ-9):
--     VQ-4: expected 5 indexes (not 6 — redundant idx_ecr_context_id removed).
--     VQ-6: authenticated SELECT only, zero INSERT/UPDATE/DELETE.
--     VQ-7: anon + authenticated have zero sequence privileges.
--     VQ-8: exactly 1 policy (ecr_admin_select).
--     VQ-9: COUNT(*) = 0 baseline.
--
-- PURPOSE
-- -------
-- Provides durable, cross-instance idempotency for estimator-backed
-- COD bookings. Guarantees that ONE encrypted pricing context
-- (identified by context_id) can successfully create AT MOST ONE
-- booking, even under:
--   - Browser retry after network failure
--   - Double-submit from the same user
--   - Concurrent race conditions (multiple serverless instances)
--   - Token replay within the 15-min TTL window
--
-- ATOMICITY MECHANISM
-- -------------------
-- The UNIQUE constraint on context_id is the single atomic gate.
-- PostgreSQL automatically creates one unique index to back this
-- constraint. No additional explicit unique index is needed or wanted.
-- Two concurrent INSERT attempts for the same context_id → exactly
-- one succeeds. The application never performs check-then-act in
-- application code — the uniqueness is enforced at database level.
--
-- context_id format: fxctx-<32 lowercase hex chars>
-- Generated by: api/estimator-v1/fixeo-estimator-runtime-v1.js
-- Used by:      api/fixeo-estimator-idempotency-v1.js
--
-- SECURITY ARCHITECTURE
-- ---------------------
-- This table is SERVER-ONLY infrastructure.
-- Inserts and updates arrive exclusively from the Vercel serverless
-- function api/server.js via api/fixeo-estimator-idempotency-v1.js,
-- which uses the Supabase SERVICE ROLE key (server-side env var,
-- never exposed to browser).
--
-- The service role bypasses RLS at the Supabase PostgREST layer,
-- so no anon or authenticated INSERT policy is needed or wanted.
--
-- Role access summary:
--   anon          -> NO access (REVOKE ALL, no policies, no sequence access)
--   authenticated -> NO write access; SELECT only for admin role via policy;
--                    no sequence access (SELECT does not require it)
--   service_role  -> unrestricted (bypasses RLS — Vercel fn + Supabase Studio)
--
-- RLS is ENABLED and FORCED as defence-in-depth.
-- If SUPABASE_SERVICE_ROLE_KEY is ever accidentally replaced with
-- the anon key, all writes will be blocked — not silently accepted.
--
-- PROFILES ADMIN CONTRACT (verified from production migration history)
-- -------------------------------------------------------------------
-- The ecr_admin_select policy uses:
--   EXISTS (SELECT 1 FROM public.profiles
--           WHERE profiles.id = auth.uid() AND profiles.role = 'admin')
--
-- This exact expression is the canonical FIXEO admin check used in:
--   enterprise_leads.sql, notifications-table-v1.sql,
--   rls-fix-2026-04-29.sql, rls-claim-requests-v1.sql,
--   rls-artisan-read-linked-requests.sql, rls-artisan-update-requests.sql,
--   rls-missions-artisan-select.sql (10+ policies total).
--
-- public.profiles has: id (UUID PK, FK to auth.users), role (TEXT).
-- It is the production name for the table created as public.users in
-- schema.sql — confirmed by rls-fix-2026-04-29.sql comment:
--   "TABLE: profiles (was: public.users in schema.sql)"
--
-- STATE MACHINE
-- -------------
-- 'acquired'  → context reserved; booking creation in progress
-- 'committed' → booking successfully created; context permanently consumed
-- 'failed'    → booking creation failed; context available for retry
--
-- Transitions:
--   [not-exists] → INSERT → 'acquired'
--   'acquired'   → PATCH  → 'committed'   (success: commit booking_ref)
--   'acquired'   → PATCH  → 'failed'      (failure: allow retry)
--   'failed'     → PATCH  → 'acquired'    (re-acquire for retry)
--
-- SAFE TO RE-RUN
-- --------------
-- All statements use IF NOT EXISTS / DROP IF EXISTS / or are idempotent.
-- Running this script twice on the same database is harmless.
-- See Section 9 for detailed re-run safety analysis.
-- ============================================================


-- ============================================================
-- SECTION 1 — CREATE TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS public.estimator_context_redemptions (

  -- Primary key (surrogate — context_id is the real identity key)
  id                bigserial     PRIMARY KEY,

  -- ── IDEMPOTENCY KEY ─────────────────────────────────────────────────────
  -- context_id is the atomic replay boundary.
  -- Format: fxctx-<32 lowercase hex chars>
  -- Generated server-side only (api/estimator-v1/fixeo-estimator-runtime-v1.js).
  -- The UNIQUE constraint in Section 2 provides database-level atomicity
  -- for concurrent INSERT attempts. Never forge-able from the browser
  -- (AES-256-GCM sealed token).
  context_id        text          NOT NULL,

  -- ── IDENTITY FIELDS (written on INSERT, used for conflict detection) ─────
  -- All three are required by consumeEstimatorContext() bookingCandidate param.
  outcome_type      text          NOT NULL,
  service_code      text          NOT NULL,
  session_id        text          NOT NULL,

  -- ── PRICE AUDIT (server-canonical, written on INSERT for admin audit) ────
  -- amount_mad is the server-authoritative canonical amount from the sealed
  -- pricing context token. Stored for audit/admin only — NOT used to re-derive
  -- booking amounts. Bookings always use the live token authority, not this.
  amount_mad        integer       NOT NULL,

  -- ── STATE MACHINE ───────────────────────────────────────────────────────
  -- Valid values: 'acquired' | 'committed' | 'failed'
  -- CHECK constraint enforces the exact values known to the runtime.
  state             text          NOT NULL DEFAULT 'acquired'
                                  CHECK (state IN ('acquired', 'committed', 'failed')),

  -- ── BOOKING BINDING (populated on commitEstimatorContext) ───────────────
  -- Set to NULL on INSERT; bound to the real booking on PATCH to 'committed'.
  -- booking_ref: COD booking reference (e.g. COD-LK3X2Y)
  -- order_id:    COD orderID from the browser request
  booking_ref       text,
  order_id          text,

  -- ── FAILURE AUDIT (populated on failEstimatorContext) ───────────────────
  -- failure_reason: up to 500 chars (truncated by runtime before storage).
  -- Set back to NULL on re-acquire (recovery path).
  failure_reason    text          CHECK (failure_reason IS NULL OR char_length(failure_reason) <= 500),

  -- ── TIMESTAMPS ──────────────────────────────────────────────────────────
  -- acquired_at: ISO timestamp of the most recent acquisition attempt.
  -- Set on INSERT and also on re-acquire (recovery path PATCH).
  acquired_at       timestamptz   NOT NULL DEFAULT now(),

  -- committed_at: ISO timestamp when context was committed (booking created).
  -- NULL until state = 'committed'.
  committed_at      timestamptz,

  -- failed_at: ISO timestamp of most recent failure.
  -- NULL until state = 'failed'. Reset to NULL on re-acquire.
  failed_at         timestamptz

);

-- Table comments
