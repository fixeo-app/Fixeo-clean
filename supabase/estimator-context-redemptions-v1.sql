-- ============================================================
-- SECTION 2 — UNIQUE CONSTRAINT (SOLE ATOMICITY MECHANISM)
-- ============================================================
-- This is the single canonical idempotency gate.
-- Concurrent INSERT for the same context_id → exactly one succeeds.
--
-- PostgreSQL creates exactly ONE unique index to back this constraint.
-- No additional explicit unique index is created (see Section 3).
-- Named explicitly for documentation and error-handling reference.

ALTER TABLE public.estimator_context_redemptions
  DROP CONSTRAINT IF EXISTS estimator_context_redemptions_context_id_unique;

ALTER TABLE public.estimator_context_redemptions
  ADD CONSTRAINT estimator_context_redemptions_context_id_unique
  UNIQUE (context_id);


-- ============================================================
-- SECTION 3 — SUPPORTING INDEXES (non-uniqueness)
-- ============================================================
-- The unique index for context_id is created implicitly by the
-- UNIQUE constraint in Section 2 and is NOT repeated here.
--
-- After this section the total index set is:
--   1. estimator_context_redemptions_pkey        (btree on id, from PRIMARY KEY)
--   2. estimator_context_redemptions_context_id_unique
--                                                (btree on context_id, from UNIQUE constraint)
--   3. idx_ecr_acquired_at                       (btree on acquired_at DESC, admin audit)
--   4. idx_ecr_state                             (btree on state, admin audit)
--   5. idx_ecr_service_code                      (btree on service_code, admin audit)
--
-- Total expected by VQ-4: 5

CREATE INDEX IF NOT EXISTS idx_ecr_acquired_at
  ON public.estimator_context_redemptions (acquired_at DESC);

CREATE INDEX IF NOT EXISTS idx_ecr_state
  ON public.estimator_context_redemptions (state);

CREATE INDEX IF NOT EXISTS idx_ecr_service_code
  ON public.estimator_context_redemptions (service_code);


-- ============================================================
-- SECTION 4 — ROW LEVEL SECURITY
-- ============================================================
-- Enable RLS (defence-in-depth).
-- service_role bypasses RLS — all Vercel fn writes go through service_role.
-- anon and authenticated cannot write to this table.
-- ENABLE and FORCE are idempotent — safe to run twice.

ALTER TABLE public.estimator_context_redemptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.estimator_context_redemptions FORCE ROW LEVEL SECURITY;


-- ============================================================
-- SECTION 5 — REVOKE ALL (anon + authenticated + sequence)
-- ============================================================

-- anon: zero table access
REVOKE ALL ON public.estimator_context_redemptions FROM anon;

-- authenticated: start from zero; selective re-grant in Section 7
REVOKE ALL ON public.estimator_context_redemptions FROM authenticated;

-- Sequence: anon and authenticated need no sequence access.
-- SELECT operations do not require sequence USAGE or SELECT.
-- service_role retains implicit unrestricted access (not affected by REVOKE).
REVOKE ALL ON SEQUENCE public.estimator_context_redemptions_id_seq FROM anon;
REVOKE ALL ON SEQUENCE public.estimator_context_redemptions_id_seq FROM authenticated;

-- Drop any previously created policies (idempotent cleanup before re-create)
DROP POLICY IF EXISTS "ecr_anon_insert"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_anon_select"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_anon_update"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_anon_delete"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_auth_insert"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_auth_update"  ON public.estimator_context_redemptions;


-- ============================================================
-- SECTION 6 — RLS POLICIES
-- ============================================================

-- 6-A: Admin SELECT — read-only audit access for authenticated admins.
-- Identified by: profiles.id = auth.uid() AND profiles.role = 'admin'
--
-- This pattern is the canonical FIXEO admin check verified from production
-- migration history (10+ existing policies across rls-fix-2026-04-29.sql,
-- enterprise_leads.sql, notifications-table-v1.sql, rls-claim-requests-v1.sql,
-- rls-artisan-*.sql, and others). public.profiles has columns:
--   id   UUID  (PK, FK to auth.users)
--   role TEXT  (values: 'admin' | 'artisan' | 'client')
--
-- Non-admin authenticated users see zero rows (policy USING = false for them).
-- service_role bypasses this entirely (unrestricted, no policy needed).
DROP POLICY IF EXISTS "ecr_admin_select" ON public.estimator_context_redemptions;

CREATE POLICY "ecr_admin_select"
  ON public.estimator_context_redemptions
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id   = auth.uid()
        AND profiles.role = 'admin'
    )
  );

-- NOTE: No authenticated INSERT, UPDATE, or DELETE policy.
-- All writes go through the Vercel fn using service_role.
-- RLS default-deny blocks any authenticated INSERT/UPDATE/DELETE.
-- No anon policy exists → anon gets zero access (RLS default-deny + REVOKE ALL).


-- ============================================================
-- SECTION 7 — GRANTS (minimal, targeted)
-- ============================================================

-- anon: zero grants (REVOKE ALL already issued in Section 5)
-- (No GRANT to anon — REVOKE is the sole statement for anon)

-- authenticated: SELECT only.
-- INSERT/UPDATE/DELETE blocked by:
--   (a) no INSERT/UPDATE/DELETE policy (RLS default-deny)
--   (b) REVOKE ALL in Section 5 + only SELECT re-granted here
GRANT SELECT ON public.estimator_context_redemptions TO authenticated;

-- Schema usage: required for authenticated to resolve table references.
-- Supabase normally grants this by default; explicit for safety.
GRANT USAGE ON SCHEMA public TO authenticated;

-- Sequence: NOT granted to authenticated or anon.
-- SELECT does not require sequence access.
-- service_role retains implicit access (INSERT uses the bigserial sequence
-- server-side only; no explicit grant needed for service_role).


