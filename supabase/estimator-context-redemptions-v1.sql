-- ============================================================
-- SECTION 9 — RE-RUN SAFETY ANALYSIS
-- ============================================================
-- Each statement class and its idempotency behavior:
--
-- CREATE TABLE IF NOT EXISTS
--   → No-op if table already exists. Columns/constraints already present
--     are preserved. New columns not added (no ALTER TABLE ADD COLUMN here).
--   → SAFE.
--
-- COMMENT ON TABLE / COLUMN
--   → Replaces existing comment. No structural change.
--   → SAFE.
--
-- DROP CONSTRAINT IF EXISTS ... / ADD CONSTRAINT ... UNIQUE
--   → DROP: no-op if constraint doesn't exist.
--   → ADD: re-creates the constraint. If constraint already exists with
--     the same name AND same definition, this is effectively idempotent
--     because DROP precedes it. If re-run on a live table with data,
--     the ADD will succeed as long as no duplicate context_id rows exist
--     (which is guaranteed by the constraint itself — if it was enforced
--     during normal operation, no duplicates can exist).
--   → SAFE (when data invariant holds — guaranteed by constraint enforcement).
--
-- CREATE INDEX IF NOT EXISTS
--   → No-op if index already exists with the same name.
--   → SAFE.
--
-- ALTER TABLE ... ENABLE ROW LEVEL SECURITY
--   → Idempotent — enabling already-enabled RLS is a no-op.
--   → SAFE.
--
-- ALTER TABLE ... FORCE ROW LEVEL SECURITY
--   → Idempotent — forcing already-forced RLS is a no-op.
--   → SAFE.
--
-- REVOKE ALL
--   → Revoking privileges that weren't granted is a no-op (no error).
--   → SAFE.
--
-- DROP POLICY IF EXISTS
--   → No-op if policy doesn't exist.
--   → SAFE.
--
-- CREATE POLICY (after DROP IF EXISTS)
--   → Always creates fresh — previous DROP ensures no "already exists" error.
--   → SAFE.
--
-- GRANT SELECT
--   → Re-granting an already-held privilege is a no-op.
--   → SAFE.
--
-- Sequence availability after bigserial CREATE TABLE IF NOT EXISTS:
--   → If table already exists, bigserial sequence was created on first run
--     and persists. REVOKE on the sequence is idempotent.
--   → If table does not yet exist, bigserial creates both table and sequence.
--   → SAFE in both cases.
--
-- CONCLUSION: This migration is safe to run twice (or more).
-- No data is deleted, no columns are dropped, no tables are dropped.


