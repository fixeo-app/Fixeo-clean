-- Drop authenticated write policies if previously created (idempotent)
DROP POLICY IF EXISTS "ecr_auth_insert"  ON public.estimator_context_redemptions;
DROP POLICY IF EXISTS "ecr_auth_update"  ON public.estimator_context_redemptions;


-- ============================================================
-- SECTION 6 — RLS POLICIES (authenticated role — admin read-only)
-- ============================================================

-- 6-A: Admin SELECT — read-only audit access for Supabase Studio admin users.
-- Non-admin authenticated users see zero rows.
-- service_role (Vercel fn, Supabase Studio as service) bypasses this entirely.
DROP POLICY IF EXISTS "ecr_admin_select" ON public.estimator_context_redemptions;

CREATE POLICY "ecr_admin_select"
  ON public.estimator_context_redemptions
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE profiles.id   = auth.uid()
        AND profiles.role = 'admin'
    )
  );

-- NOTE: No authenticated INSERT, UPDATE, or DELETE policy.
-- All writes go through the Vercel fn using service_role.
-- RLS default-deny blocks any authenticated INSERT/UPDATE/DELETE.
-- No anon policy exists → anon gets zero access.


-- ============================================================
-- SECTION 7 — GRANTS
-- ============================================================

-- anon: NO grants (REVOKE ALL already issued above)
REVOKE ALL ON public.estimator_context_redemptions FROM anon;

-- authenticated: SELECT only (INSERT/UPDATE/DELETE blocked by RLS default-deny + no policies)
-- Admin SELECT is additionally gated by the ecr_admin_select policy.
GRANT SELECT ON public.estimator_context_redemptions TO authenticated;

-- service_role: Supabase grants this implicitly; explicit GRANT not required.
-- The Vercel fn uses service_role → bypasses RLS → INSERT/UPDATE/RETURNING work.

-- Schema usage (Supabase default — usually already granted)
GRANT USAGE ON SCHEMA public TO authenticated;

-- Sequence: service_role needs this for bigserial INSERT
GRANT USAGE, SELECT ON SEQUENCE public.estimator_context_redemptions_id_seq TO authenticated;


