'use strict';
/**
 * artisan-card-v3.js — Canonical FIXEO Artisan Card V3
 * ======================================================
 * Renders ONE static artisan profile card from structured data.
 * Clean-room component. Zero dependency on:
 *   - artisan-card-conversion-v1.css (frozen)
 *   - fixeo-local-flagship-v1.js (runtime)
 *   - fixeo-artisan-directory-v1.js (runtime)
 *   - any reservation / RAFI / booking system
 *
 * PURPOSE:
 *   Server-side/generation-time HTML for SEO V3 pages.
 *   This module is consumed by V3 generators that want to
 *   embed a static artisan card before JS hydration.
 *   It is NOT a runtime rendering engine.
 *
 * OUTPUT:
 *   A self-contained <article class="fxseo-card-v3 …"> string.
 *   No external CSS URLs, no JS event handlers, no inline scripts.
 *
 * DATA CONTRACT — FIELD CLASSIFICATION:
 *   See PUBLIC_FIELDS / buildArtisanCard() JSDoc below.
 *
 * VERSION HISTORY:
 *   v3-a1 (2026-09-10): Initial implementation.
 *   v3-a2 (2026-09-10): Task 2.4A corrections:
 *     - Issue 1: Removed legacy ?id= profile URL fallback.
 *       publicSlug is now the ONLY source for a profile CTA.
 *       id is no longer an accepted API field; it is FORBIDDEN.
 *       Rationale: SEO V3 must strengthen canonical internal linking.
 *       Propagating /artisan-profile.html?id= legacy URLs across generated
 *       SEO pages is not an approved V3 internal-link strategy.
 *     - Issue 2: Description truth-guard rewritten.
 *       Old behavior: sanitizeDesc() silently removed banned phrases
 *       (e.g. "Artisan vérifié disponible immédiatement" → "Artisan disponible")
 *       — a silent partial rewrite that could output mutilated, misleading text.
 *       New behavior: plainTextDesc() strips HTML only → normalizes whitespace →
 *       content-guard BANNED_TERMS check → if ANY banned term found: return null
 *       → description block is omitted entirely. No surgical phrase removal.
 *       Rationale: a bad description should not be silently laundered; it should
 *       be surfaced to data team and omitted from public output.
 *
 * PROFILE URL STRATEGY (v3-a2, confirmed from vercel.json):
 *   /artisan/{public_slug}   → routes to /api/artisan-profile-fn?slug=
 *   This is the ONLY canonical public artisan URL in SEO V3.
 *   Missing/invalid publicSlug → no profile CTA (graceful degradation).
 *   Legacy /artisan-profile.html?id= is NOT generated by V3.
 *
 * DESCRIPTION TRUTH-GUARD (v3-a2):
 *   Phase 1: strip HTML tags (security, no injection risk)
 *   Phase 2: normalize whitespace to plain text
 *   Phase 3: check against content-guard BANNED_TERMS (same guard as all V3 generators)
 *   Phase 4: if clean — escape and truncate to DESC_MAX_LENGTH chars
 *   Phase 5: if banned term found — return null → description block omitted
 *   This is DETECTION + OMISSION, not detection + rewrite.
 *
 * RATINGS / REVIEWS:
 *   NOT rendered. Intentional product-truth decision, mirroring the
 *   artisan-card-conversion-v1.css V3B documented rationale:
 *   "Rating is NOT displayed — only show when genuine rating>0 AND
 *   reviews>0, and the data reliability does not yet meet that bar."
 *   When data is reliable, a future task can add the rating block.
 *
 * BANNED CLAIMS (per Q2 + Q11 decisions):
 *   vérifié, qualifié, certifié (in credential context),
 *   disponible immédiatement, 24h/7, réponse garantie,
 *   devis gratuit, meilleur artisan, top artisan.
 *   Approved: "profil référencé sur FIXEO", "paiement après intervention".
 *
 * FILE: seo/generators/shared/artisan-card-v3.js
 * Version: v3-a2 · 2026-09-10
 */

// ── Content-guard integration ─────────────────────────────────────────────────
// Import BANNED_TERMS only — do not call check() (which throws); we detect
// and omit rather than throw, since a bad DB description should not abort
// the entire page generation.

const { BANNED_TERMS } = require('./content-guard');

// ── Constant maps (mirrors fixeo-local-flagship-v1.js / fixeo-artisan-directory-v1.js) ──

const SVC_LABELS = {
  plomberie:    'Plomberie',
  electricite:  'Électricité',
  serrurerie:   'Serrurerie',
  climatisation:'Climatisation',
  peinture:     'Peinture',
  menuiserie:   'Menuiserie',
  maconnerie:   'Maçonnerie',
  nettoyage:    'Nettoyage',
};

const SVC_ICONS = {
  plomberie:    '🔧',
  electricite:  '⚡',
  serrurerie:   '🔑',
  climatisation:'❄️',
  peinture:     '🎨',
  menuiserie:   '🪵',
  maconnerie:   '🧱',
  nettoyage:    '🧹',
};

// ── Description constants ─────────────────────────────────────────────────────

const DESC_MAX_LENGTH = 160; // characters before truncation with ellipsis

// ── URL-safe slug validation ──────────────────────────────────────────────────

// Valid public_slug: 4–120 lowercase alphanumeric + hyphens
const SLUG_RE = /^[a-z0-9][a-z0-9-]{2,118}[a-z0-9]$/;

// Valid HTTPS photo URL: must start with https://, no spaces or injection chars
const PHOTO_URL_RE = /^https:\/\/[^\s"'<>]+$/;

// Forbidden href schemes
const UNSAFE_HREF_RE = /^(javascript:|data:|vbscript:)/i;

// ── HTML escape ───────────────────────────────────────────────────────────────

/**
 * Escape characters that have meaning in HTML contexts.
 * Handles null/undefined safely.
 * @param {*} val
 * @returns {string}
 */
function esc(val) {
  return String(val == null ? '' : val).replace(/[&<>"']/g, c => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  }[c]));
}

// ── URL validation helpers ────────────────────────────────────────────────────

/**
 * Validate a public_slug value.
 * @param {string} slug
 * @returns {boolean}
 */
function isValidSlug(slug) {
  return typeof slug === 'string' && SLUG_RE.test(slug);
}

/**
 * Validate a public photo URL.
 * Must be HTTPS. No data: or javascript: allowed.
 * @param {string} url
 * @returns {boolean}
 */
function isValidPhotoUrl(url) {
  if (typeof url !== 'string' || !url) return false;
  if (UNSAFE_HREF_RE.test(url)) return false;
  return PHOTO_URL_RE.test(url);
}

/**
 * Validate a canonical profile href.
 * Must start with / or https://www.fixeo.ma/. No unsafe schemes.
 * @param {string} href
 * @returns {boolean}
 */
function isValidProfileHref(href) {
  if (typeof href !== 'string' || !href) return false;
  if (UNSAFE_HREF_RE.test(href)) return false;
  return href.startsWith('/') || href.startsWith('https://www.fixeo.ma/');
}

// ── Description truth-guard pipeline (v3-a2) ─────────────────────────────────

/**
 * normalise() — mirror of content-guard's internal _normalise():
 * lowercase + collapse apostrophe variants.
 * Must stay in sync with content-guard.js _normalise() implementation.
 * @param {string} s
 * @returns {string}
 */
function _normalise(s) {
  return s.toLowerCase().replace(/[\u2019\u2018']/g, "'");
}

/**
 * plainTextDesc() — Phase 1+2 of the description pipeline.
 * Strips HTML tags and normalizes whitespace to produce plain text.
 * Does NOT remove any content-bearing phrases. Does NOT truncate.
 * @param {string|null|undefined} raw
 * @returns {string} plain text, may be empty string
 */
function plainTextDesc(raw) {
  if (!raw) return '';
  let s = String(raw);
  // Strip HTML tags — no risk of injection, output is plain text
  s = s.replace(/<[^>]*>/g, ' ');
  // Normalize whitespace
  s = s.replace(/\s+/g, ' ').trim();
  return s;
}

/**
 * descriptionForCard() — Full description truth-guard pipeline.
 *
 * Pipeline (v3-a2 — DETECTION + OMISSION, no surgical rewrite):
 *   1. plainTextDesc(): strip HTML, normalize whitespace
 *   2. Check resulting plain text against content-guard BANNED_TERMS
 *   3. If ANY banned term found: return null (caller omits description block)
 *   4. If clean: escape and truncate to DESC_MAX_LENGTH chars
 *   5. Return escaped, safe, truncated string
 *
 * This replaces the old sanitizeDesc() which removed banned phrases
 * and could produce mutilated sentences like "Artisan disponible"
 * from an input of "Artisan vérifié disponible immédiatement".
 *
 * @param {string|null|undefined} raw  — raw description from DB
 * @returns {string|null}
 *   string — safe, escaped, display-ready
 *   null   — description contained a banned term; omit the block entirely
 */
function descriptionForCard(raw) {
  // Phase 1+2: strip HTML, normalize whitespace
  const plain = plainTextDesc(raw);

  // Empty — nothing to show
  if (!plain) return null;

  // Phase 3: truth-guard check against content-guard BANNED_TERMS
  const normalised = _normalise(plain);
  for (const term of BANNED_TERMS) {
    if (normalised.includes(term)) {
      // Banned term detected — omit description entirely (no rewrite, no fragment)
      return null;
    }
  }

  // Phase 4: truncate clean plain text
  let safe = plain;
  if (safe.length > DESC_MAX_LENGTH) {
    safe = safe.slice(0, DESC_MAX_LENGTH).replace(/\s+\S*$/, '').trim() + '\u2026';
  }

  // Phase 5: escape for HTML output
  return esc(safe);
}

// ── Service label / icon helpers ──────────────────────────────────────────────

function svcLabel(slug) {
  const normalized = (slug || '').toLowerCase().trim();
  return SVC_LABELS[normalized] || (slug ? slug.charAt(0).toUpperCase() + slug.slice(1) : '');
}

function svcIcon(slug) {
  const normalized = (slug || '').toLowerCase().trim();
  return SVC_ICONS[normalized] || '🔧';
}

// ── Profile URL builder (v3-a2 — publicSlug ONLY) ────────────────────────────

/**
 * Build the canonical profile URL for a V3 card.
 *
 * v3-a2: publicSlug is the ONLY source for a profile CTA.
 * Legacy /artisan-profile.html?id= is NOT generated by V3.
 *
 * Strategy:
 *   valid publicSlug → /artisan/{publicSlug}
 *   missing/invalid  → null (card renders without profile CTA)
 *
 * @param {string|null} publicSlug
 * @returns {string|null}
 */
function buildProfileHref(publicSlug) {
  if (isValidSlug(publicSlug)) {
    return '/artisan/' + publicSlug;
  }
  return null;
}

// ── Photo / fallback builder ──────────────────────────────────────────────────

/**
 * Build the avatar section HTML.
 * Strategy:
 *   1. Real photo URL (must be valid HTTPS, from photo_url field)
 *   2. Initials fallback: first letter of name on gradient surface
 * No gender/race/appearance assumptions. No illustrative hero injection
 * (that is a runtime JS concern — fixeo-heroes.js not available at gen time).
 * @param {string|null} photoUrl  — validated HTTPS photo URL or null
 * @param {string}      name      — already HTML-escaped artisan name
 * @param {string}      catSlug   — service category slug (for CSS data-category)
 * @param {string}      catIcon   — emoji for badge
 * @returns {string} HTML
 */
function buildAvatarHtml(photoUrl, name, catSlug, catIcon) {
  const escapedCat  = esc(catSlug);
  const escapedIcon = esc(catIcon);

  let imgHtml;
  let avatarState;

  if (photoUrl && isValidPhotoUrl(photoUrl)) {
    avatarState = 'real-photo';
    imgHtml = ''
      + '<img class="fxseo-card-v3__avatar-img"'
      + ' src="' + esc(photoUrl) + '"'
      + ' alt="Photo de ' + name + '"'
      + ' width="56" height="56" loading="lazy" decoding="async"'
      + ' data-avatar-type="real-photo"'
      + '>';
  } else {
    avatarState = 'initials';
    // De-escape HTML entities to get the raw first character
    const rawName = String(name || '').replace(/&[a-z]+;/gi, '').replace(/&#\d+;/gi, '');
    const initial = rawName.trim().charAt(0).toUpperCase() || 'A';
    imgHtml = '<span class="fxseo-card-v3__avatar-initials" aria-hidden="true">'
      + esc(initial)
      + '</span>';
  }

  return '<div class="fxseo-card-v3__avatar" data-category="' + escapedCat + '" data-avatar-state="' + avatarState + '" aria-hidden="true">'
    + imgHtml
    + '<span class="fxseo-card-v3__avatar-badge" aria-hidden="true">' + escapedIcon + '</span>'
    + '</div>';
}

// ── Price block builder ───────────────────────────────────────────────────────

/**
 * Build price display HTML.
 * Shows price only when actual data is present (price_from or price_label).
 * Never invents or defaults a price. No guaranteed/fixed-price wording.
 *
 * price_label (pre-formatted DB string) takes priority over price_from.
 * "Tarif indicatif" hint added when deriving from price_from — makes
 * clear this is an indicative, not a guaranteed/fixed price.
 *
 * @param {number|null}  priceFrom   — e.g. 120
 * @param {string|null}  priceLabel  — e.g. "À partir de 120 DH"
 * @returns {string} HTML or empty string
 */
function buildPriceHtml(priceFrom, priceLabel) {
  let main = '';
  let hint = '';

  if (priceLabel && String(priceLabel).trim()) {
    // DB already has a pre-formatted string — use as-is, no hint
    main = String(priceLabel).trim();
    hint = '';
  } else if (priceFrom != null && priceFrom > 0) {
    main = '\u00c0 partir de\u00a0' + Math.round(priceFrom) + '\u00a0MAD';
    hint = 'Tarif indicatif'; // explicit: not a fixed or guaranteed price
  }

  if (!main) return '';

  return '<div class="fxseo-card-v3__price">'
    + '<span class="fxseo-card-v3__price-main">' + esc(main) + '</span>'
    + (hint ? '<span class="fxseo-card-v3__price-hint">' + esc(hint) + '</span>' : '')
    + '</div>';
}

