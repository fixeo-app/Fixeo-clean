// ── Main export ───────────────────────────────────────────────────────────────

/**
 * buildArtisanCard — render a canonical FIXEO V3 artisan card.
 *
 * PUBLIC FIELD CONTRACT (v3-a2)
 * ──────────────────────────────
 * REQUIRED:
 *   name         {string}         Artisan display name (public). Must be non-empty.
 *   serviceLabel {string}         Human label: "Plomberie", "Électricité", etc.
 *   cityLabel    {string}         Human city name: "Casablanca", "Rabat", etc.
 *
 * OPTIONAL (all safe to omit — card degrades gracefully):
 *   serviceSlug  {string}         Slug for CSS data-category + icon lookup.
 *                                 E.g. "plomberie", "electricite".
 *                                 Defaults to empty (generic icon).
 *   photoUrl     {string|null}    Public HTTPS photo URL.
 *                                 Validated: must start with https://.
 *                                 Rejected: data:, javascript:, non-HTTPS.
 *                                 Omit if not a confirmed public-safe URL.
 *   publicSlug   {string|null}    Artisan's public_slug from Supabase.
 *                                 Used to build /artisan/{slug} clean URL.
 *                                 Must match /^[a-z0-9][a-z0-9-]{2,118}[a-z0-9]$/.
 *                                 ONLY source for profile CTA in V3.
 *   description  {string|null}    Public description from Supabase.
 *                                 Truth-guarded: HTML stripped, then checked
 *                                 against content-guard BANNED_TERMS.
 *                                 If any banned term found: description omitted.
 *                                 If clean: escaped and truncated at DESC_MAX_LENGTH.
 *   priceFrom    {number|null}    Numeric price floor (MAD). E.g. 120.
 *                                 Rendered as "À partir de 120 MAD · Tarif indicatif".
 *                                 Never rendered when null/zero/negative.
 *   priceLabel   {string|null}    Pre-formatted price string from DB.
 *                                 Takes precedence over priceFrom when present.
 *
 * DERIVED (computed internally — do not pass):
 *   profileHref    — built from publicSlug only (v3-a2: no id fallback)
 *   catIcon        — looked up from serviceSlug
 *   descriptionOut — computed from description via descriptionForCard()
 *
 * FORBIDDEN (hard throw if passed):
 *   id / legacy_id / _supabase_id — internal DB identifiers.
 *     In v3-a2: id removed from API. Its former role (legacy profile URL
 *     fallback) is not an approved V3 internal-link strategy.
 *   phone / telephone       — private contact
 *   email                   — private contact
 *   owner_user_id           — auth / admin
 *   verified (boolean)      — never show "artisan vérifié" badge
 *   verifie                 — same
 *   claim_status            — internal state
 *   onboarding_completed    — internal state
 *   commission              — commercial/internal
 *   pricing_margin          — commercial/internal
 *   admin_notes             — internal
 *   response_time_min       — cannot guarantee; never show response time claims
 *   responseTime            — same
 *   rating / note           — not shown (product-truth decision)
 *   reviews / reviewCount / avis — not shown
 *   availability / disponibilite / available — not shown
 *   created_at / updated_at — internal timestamps
 *
 * @param {object} opts
 * @param {string}            opts.name
 * @param {string}            opts.serviceLabel
 * @param {string}            opts.cityLabel
 * @param {string}           [opts.serviceSlug]
 * @param {string|null}      [opts.photoUrl]
 * @param {string|null}      [opts.publicSlug]
 * @param {string|null}      [opts.description]
 * @param {number|null}      [opts.priceFrom]
 * @param {string|null}      [opts.priceLabel]
 * @returns {string} HTML string for one artisan card
 */
function buildArtisanCard(opts) {
  if (!opts || typeof opts !== 'object') {
    throw new TypeError('artisan-card-v3: opts must be a plain object');
  }

  // ── Validate required fields ────────────────────────────────────────────────

  const name = String(opts.name || '').trim();
  if (!name) throw new Error('artisan-card-v3: name is required and must be non-empty');

  const serviceLabel = String(opts.serviceLabel || '').trim();
  if (!serviceLabel) throw new Error('artisan-card-v3: serviceLabel is required and must be non-empty');

  const cityLabel = String(opts.cityLabel || '').trim();
  if (!cityLabel) throw new Error('artisan-card-v3: cityLabel is required and must be non-empty');

  // ── Validate forbidden fields ───────────────────────────────────────────────

  const FORBIDDEN = [
    // v3-a2: id removed from API — not an approved V3 internal-link strategy
    'id', 'legacy_id', '_supabase_id',
    'phone', 'telephone', 'email',
    'owner_user_id',
    'verified', 'verifie',
    'claim_status', 'onboarding_completed',
    'commission', 'pricing_margin', 'admin_notes',
    'response_time_min', 'responseTime',
    'rating', 'note', 'reviews', 'reviewCount', 'avis',
    'availability', 'disponibilite', 'available',
    'created_at', 'updated_at',
  ];

  FORBIDDEN.forEach(field => {
    if (Object.prototype.hasOwnProperty.call(opts, field)) {
      throw new Error('artisan-card-v3: forbidden field "' + field + '" must not be passed to buildArtisanCard');
    }
  });

  // ── Optional fields ─────────────────────────────────────────────────────────

  const serviceSlug = String(opts.serviceSlug || '').toLowerCase().trim();
  const photoUrl    = opts.photoUrl   || null;
  const publicSlug  = opts.publicSlug || null;
  const description = opts.description || null;
  const priceFrom   = (opts.priceFrom != null && Number.isFinite(Number(opts.priceFrom)) && Number(opts.priceFrom) > 0)
    ? Number(opts.priceFrom) : null;
  const priceLabel  = opts.priceLabel || null;

  // ── Derived values ──────────────────────────────────────────────────────────

  const catSlug      = serviceSlug || 'autre';
  const catIcon      = svcIcon(catSlug);
  const catLabel     = serviceLabel;

  const escapedName     = esc(name);
  const escapedCity     = esc(cityLabel);
  const escapedCatLabel = esc(catLabel);

  // v3-a2: publicSlug only — no id fallback
  const profile = buildProfileHref(publicSlug);

  // v3-a2: truth-guard pipeline — returns escaped string or null
  const descOut = descriptionForCard(description);

  // ── Build sub-sections ──────────────────────────────────────────────────────

  const avatarHtml = buildAvatarHtml(photoUrl, escapedName, catSlug, catIcon);

  // descOut is already escaped (by descriptionForCard) — do NOT double-escape
  const descHtml = descOut !== null
    ? '<p class="fxseo-card-v3__desc">' + descOut + '</p>'
    : '';

  const priceHtml = buildPriceHtml(priceFrom, priceLabel);
  const trustHtml = buildTrustHtml();

  // Profile CTA — only rendered when a valid canonical slug URL exists
  let profileCtaHtml = '';
  if (profile && isValidProfileHref(profile)) {
    profileCtaHtml = '<a class="fxseo-card-v3__profile-link"'
      + ' href="' + esc(profile) + '"'
      + ' aria-label="Voir le profil de ' + escapedName + ', ' + escapedCatLabel + ' \u00e0 ' + escapedCity + '">'
      + 'Voir le profil\u00a0\u203a'
      + '</a>';
  }

  // ── Assemble card ───────────────────────────────────────────────────────────

  return '<article class="fxseo-card-v3"'
    + ' aria-label="' + escapedName + ', ' + escapedCatLabel + ' \u00e0 ' + escapedCity + '">'

    // Header: avatar + identity
    + '<div class="fxseo-card-v3__header">'
    + avatarHtml
    + '<div class="fxseo-card-v3__identity">'
    + '<h3 class="fxseo-card-v3__name">' + escapedName + '</h3>'
    + '<div class="fxseo-card-v3__meta">'
    + '<span class="fxseo-card-v3__meta-service">'
    + esc(catIcon) + '\u00a0' + escapedCatLabel
    + '</span>'
    + '<span class="fxseo-card-v3__meta-sep" aria-hidden="true">\u00b7</span>'
    + '<span class="fxseo-card-v3__meta-city">'
    + '\uD83D\uDCCD\u00a0' + escapedCity
    + '</span>'
    + '</div>'
    + '</div>'
    + '</div>'

    // Description (optional — omitted if null or if truth-guard found banned term)
    + descHtml

    // Trust rows
    + trustHtml

    // Action area: optional price + optional profile link
    + '<div class="fxseo-card-v3__action">'
    + '<div class="fxseo-card-v3__divider" aria-hidden="true"></div>'
    + priceHtml
    + profileCtaHtml
    + '</div>'

    + '</article>';
}

